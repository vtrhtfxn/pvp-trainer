function slab(m: number): string {
  return ['smooth_stone', 'sandstone', 'oak', 'cobblestone', 'brick', 'stone_brick', 'nether_brick', 'quartz'][m] ?? 'smooth_stone';
}

function doubleSlab(m: number): string {
  return ['smooth_stone', 'sandstone', 'oak_planks', 'cobblestone', 'bricks', 'stone_bricks', 'nether_bricks', 'quartz_block'][m & 7] ?? 'smooth_stone';
}

/** Stairs keep which half they sit in (meta bit 4: upside down). */
function stairs(material: string, m: number): string {
  return `${material}_stairs[half=${m & 4 ? 'top' : 'bottom'}]`;
}

/** Today's name for an old numeric block id and its metadata. */
export function legacyName(id: number, meta: number): string {
  const e = ID[id];
  if (e === undefined) return id === 0 ? 'air' : 'stone';
  return typeof e === 'string' ? e : e(meta & 15);
}
